"""Builds ``app/data/skills_onet.txt`` from O*NET's "Technology Skills" file.

Run by hand, rarely; the result is committed. The laptop never needs network at runtime.

    curl -o "Technology Skills.txt" \
      "https://www.onetcenter.org/dl_files/database/db_29_3_text/Technology%20Skills.txt"
    uv run python -m scripts.build_skill_list "Technology Skills.txt"

O*NET data is licensed CC BY 4.0 (https://www.onetcenter.org/license_db.html); the output
file carries the attribution. Keeps names listed for at least ``MIN_OCCUPATIONS`` occupations
or marked "Hot Technology", drops generic category names ("Spreadsheet software"), and
orders by how many occupations list them.
"""

from __future__ import annotations

import csv
import sys
from collections import Counter
from pathlib import Path

MIN_OCCUPATIONS = 3
MAX_NAME_LENGTH = 40
OUTPUT = Path(__file__).resolve().parent.parent / "app" / "data" / "skills_onet.txt"
HEADER = (
    "# Technology and tool names from O*NET (https://www.onetcenter.org), by the U.S. Department\n"
    "# of Labor, Employment and Training Administration (USDOL/ETA). Licensed CC BY 4.0:\n"
    "# https://creativecommons.org/licenses/by/4.0/. Modified: filtered and re-ordered.\n"
    "# Generated by scripts/build_skill_list.py; do not edit by hand. Most common first.\n"
)
GENERIC_SUFFIXES = ("software", "system", "systems", "platform", "tools")


def build(source: Path) -> list[str]:
    counts: Counter[str] = Counter()
    hot: set[str] = set()
    with source.open(encoding="utf-8", newline="") as handle:
        for row in csv.DictReader(handle, delimiter="\t"):
            name = row["Example"].strip()
            counts[name] += 1
            if row["Hot Technology"] == "Y":
                hot.add(name)
    kept = [
        name
        for name, count in counts.most_common()
        if (count >= MIN_OCCUPATIONS or name in hot)
        and len(name) <= MAX_NAME_LENGTH
        and not name.lower().endswith(GENERIC_SUFFIXES)
    ]
    return kept


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        sys.stderr.write(f"{__doc__}\n")
        return 2
    names = build(Path(argv[1]))
    OUTPUT.write_text(HEADER + "\n".join(names) + "\n", encoding="utf-8")
    sys.stdout.write(f"Wrote {len(names)} names to {OUTPUT}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
